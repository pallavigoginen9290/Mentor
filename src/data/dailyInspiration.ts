  const dayOfYear = Math.floor((now.getTime() - startOfYear.getTime()) / (1000 * 60 * 60 * 24));
  const effectiveDay = dayOfYear + dayOffset;

  const quoteIdx = ((effectiveDay % DAILY_QUOTES.length) + DAILY_QUOTES.length) % DAILY_QUOTES.length;
